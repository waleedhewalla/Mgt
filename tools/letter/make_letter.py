def run(p, text, size=14, bold=False, color=INK, italic=False):
    r = p.add_run(text)
    r.font.name = FONT
    rp = r._r.get_or_add_rPr()
    rf = rp.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rp.insert(0, rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rf.set(qn(a), FONT)
    if bold:
        r.bold = True
        rp.append(OxmlElement('w:bCs'))
    r.font.color.rgb = RGBColor.from_string(color)
    r.font.size = Pt(size)
    szcs = OxmlElement('w:szCs'); szcs.set(qn('w:val'), str(int(size * 2))); rp.append(szcs)
    rp.append(OxmlElement('w:rtl'))
    return r


def para(text='', size=14, bold=False, color=INK, align=None, before=0, after=100, keep=False, container=None):
    p = (container or doc).add_paragraph()
    pf = p.paragraph_format
    pf.space_before, pf.space_after = Pt(before / 20 * 1), Pt(after / 20 * 1)
    if align == 'center':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == 'justify':
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if keep:
        pf.keep_with_next = True
    if text:
        run(p, text, size, bold, color)
    return p


def rich(parts, size=14, align='justify', after=120, container=None):
    """parts: list of (text, bold, color)"""
    p = para(size=size, align=align, after=after, container=container)
    for t in parts:
        text, b, c = (t + (False, INK))[:3] if isinstance(t, tuple) else (t, False, INK)
        run(p, text, size, b, c)
    return p


def border(p, side='bottom', color=GOLD, sz=12, space=4):
    pPr = p._p.get_or_add_pPr()
    bdr = pPr.find(qn('w:pBdr'))
    if bdr is None:
        bdr = OxmlElement('w:pBdr'); pPr.append(bdr)
    e = OxmlElement(f'w:{side}')
    for k, v in (('w:val', 'single'), ('w:sz', str(sz)), ('w:space', str(space)), ('w:color', color)):
        e.set(qn(k), v)
    bdr.append(e)


def shade(p, fill):
    pPr = p._p.get_or_add_pPr()
    s = OxmlElement('w:shd'); s.set(qn('w:val'), 'clear'); s.set(qn('w:color'), 'auto'); s.set(qn('w:fill'), fill)
    pPr.append(s)


def h1(text):
    p = para(text, 20, True, GREEN, before=0, after=60, keep=True)
    border(p, 'bottom', GOLD, 18, 6)
    return p


def h2(text):
    p = para(text, 16, True, GREEN, before=200, after=80, keep=True)
    return p


def label(text):
    return para(text, 14, True, GREEN, before=120, after=40, keep=True)


def bullets(items, size=13.5):
    for it in items:
        p = para(size=size, align='justify', after=50)
        p.paragraph_format.right_indent = Cm(0.6)  # bidi paragraph: indent on the reading side
        p.paragraph_format.first_line_indent = Cm(-0.45)
        run(p, '◆  ', 9, False, GOLD)
        if isinstance(it, tuple):
            run(p, it[0], size, True, GREEN); run(p, it[1], size)
        else:
            run(p, it, size)


def numbered(items, start=1, size=13.5):
    for i, it in enumerate(items, start):
        p = para(size=size, after=30)
        p.paragraph_format.right_indent = Cm(0.6)
        p.paragraph_format.first_line_indent = Cm(-0.6)
        run(p, f'{i}.  ', size, True, GOLD)
        run(p, it, size)


def cell_text(cell, text, bold=False, color=INK, size=12.5, fill=None, align=None):
    cell.paragraphs[0].text = ''
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    if align == 'center':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run(p, text, size, bold, color)
    if fill:
        tcPr = cell._tc.get_or_add_tcPr()
        s = OxmlElement('w:shd'); s.set(qn('w:val'), 'clear'); s.set(qn('w:color'), 'auto'); s.set(qn('w:fill'), fill)
        tcPr.append(s)


def table(rows, widths, header=True, label_col=False):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    tblPr = t._tbl.tblPr
    tblPr.append(OxmlElement('w:bidiVisual'))
    borders = OxmlElement('w:tblBorders')
    for side in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        e = OxmlElement(f'w:{side}')
        if side in ('left', 'right', 'insideV'):
            e.set(qn('w:val'), 'nil')
        else:
            for k, v in (('w:val', 'single'), ('w:sz', '4'), ('w:space', '0'), ('w:color', 'C9D3C4')):
                e.set(qn(k), v)
        borders.append(e)
    tblPr.append(borders)
    total = sum(int(Cm(w).twips) if hasattr(Cm(w), 'twips') else int(w * 567) for w in widths)
    tw = tblPr.find(qn('w:tblW')); tw.set(qn('w:type'), 'dxa'); tw.set(qn('w:w'), str(total))
    lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); tblPr.append(lay)
    for gc, w in zip(t._tbl.tblGrid.findall(qn('w:gridCol')), widths):
        gc.set(qn('w:w'), str(int(w * 567)))
    for i, r in enumerate(rows):
        for j, txt in enumerate(r):
            c = t.cell(i, j)
            c.width = Cm(widths[j])
            if header and i == 0:
                cell_text(c, txt, True, 'FFFFFF', 12.5, GREEN)
            elif label_col and j == 0:
                cell_text(c, txt, True, GREEN, 12.5, PALE)
            else:
                cell_text(c, txt, False, INK, 12.5)
    para(after=60)
    return t


def page_break():
    p = doc.add_paragraph()
    p.add_run().add_break(WD_BREAK.PAGE)


def field(p, instr):
    for kind in ('begin', None, 'end'):
        r = p.add_run()
        if kind:
            fc = OxmlElement('w:fldChar'); fc.set(qn('w:fldCharType'), kind); r._r.append(fc)
        else:
            it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = instr; r._r.append(it)


