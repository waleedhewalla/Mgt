def book_page(no, ordinal, title, question, offers_intro, offers, unique, reader, facts):
    page_break()
    p = para(f'المرفق {no}', 12, True, GOLD, after=0)
    h1(f'الكتاب {ordinal}')
    para(title, 17, True, INK, after=160)
    label('السؤال الذي يجيب عنه')
    rich([question])
    label('ما يقدّمه')
    if offers_intro:
        rich([offers_intro], after=60)
    bullets(offers)
    label('ما يميّزه')
    rich([unique])
    label('القارئ')
    rich([reader])
    table([['البيان', 'القيمة']] + facts, [3.6, 13.0])


def toc_page(ordinal, front, parts, back):
    page_break()
    h1(f'فهرس الكتاب {ordinal}')
    if front:
        rich([(front[0], True, GREEN), front[1]], size=13, after=100)
    n = 1
    for name, chapters in parts:
        label(name)
        numbered(chapters, n, 13)
        n += len(chapters)
    for k, v in back:
        rich([(k, True, GREEN), v], size=13, after=60)


