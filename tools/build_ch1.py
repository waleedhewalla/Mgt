def set_text(p, text):
    """Replace a paragraph's text, keeping its paragraph props and first run's formatting."""
    runs = p.findall(q('r'))
    tmpl = next((r for r in runs if ''.join(t.text or '' for t in r.iter(q('t'))).strip()), runs[0])
    rpr = tmpl.find(q('rPr'))
    for r in runs:
        p.remove(r)
    r = etree.SubElement(p, q('r'))
    if rpr is not None:
        r.append(copy.deepcopy(rpr))
    t = etree.SubElement(r, q('t'))
    t.text = text
    t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    return p


def set_runs(p, parts):
    """parts: list of (text, run) — each new run copies formatting from the given original run."""
    runs = p.findall(q('r'))
    rprs = [copy.deepcopy(src.find(q('rPr'))) for _, src in parts]
    for r in runs:
        p.remove(r)
    for (text, _), rpr in zip(parts, rprs):
        r = etree.SubElement(p, q('r'))
        if rpr is not None:
            r.append(rpr)
        t = etree.SubElement(r, q('t'))
        t.text = text
        t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')


def cell_p(tbl, row, col, idx=0):
    tr = tbl.findall(q('tr'))[row]
    return tr.findall(q('tc'))[col].findall(q('p'))[idx]


def cell_text(tbl, row, col, text):
    set_text(cell_p(tbl, row, col), text)


W14 = 'http://schemas.microsoft.com/office/word/2010/wordml'


def fresh(el):
    for e in el.iter():
        for a in ('paraId', 'textId'):
            e.attrib.pop('{%s}%s' % (W14, a), None)
    return el


def clone_after(el, text):
    new = fresh(copy.deepcopy(el))
    set_text(new, text)
    el.addnext(new)
    return new


