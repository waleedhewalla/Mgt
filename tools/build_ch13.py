def runs_of(p):
    return [r for r in p.findall(q('r')) if ''.join(t.text or '' for t in r.iter(q('t')))]


def numbered(p, text):
    """Keep the circled number and its spacer run, replace the rest with one run."""
    r = runs_of(p)
    set_runs(p, [(ptext(r[0]), r[0]), (ptext(r[1]), r[1]), (text, r[2])])


def cite(p, text):
    """In-text reference line: indent run + text run."""
    r = runs_of(p)
    set_runs(p, [(ptext(r[0]), r[0]), (text, r[1])])


def ref(p, n, text):
    r = runs_of(p)
    set_runs(p, [(f'{n}.  ', r[0]), (text, r[1])])


def body_para(text, like):
    p = fresh(copy.deepcopy(K[like])); set_text(p, text); return p


