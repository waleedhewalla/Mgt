import json,re
U=json.load(open('units.json',encoding='utf-8'))
ORD={'الأول':1,'الثاني':2,'الثالث':3,'الرابع':4,'الخامس':5,'السادس':6,'السابع':7,'الثامن':8,'التاسع':9,'العاشر':10,'الحادي عشر':11,'الثاني عشر':12,'الثالث عشر':13,'الرابع عشر':14}
KW={1:['أقومية','الابستيمولوج','حدود الادعاء','القولبة','دستور'],2:['التيار','أسلمة المعرفة','القولبة','الإخفاق','خريطة الفكر'],3:['الفرضية الصفرية','الأصالة','الاستقلالية','التمييز','المحك','الباحث المقيد','اختبار'],
4:['هرم','المصادر','السنة','مدارس','السيرة','الطباطبائي','المرجعية','العدل'],5:['السلم','الاشتقاق','البطاقة','المقاصد','المستوى','الحقول','الشورى','الأمانة','هامش'],6:['البروتوكول','القراءة','الخطوات','المحكم','الاستقراء','الإحسان'],
7:['التعارض','الشذوذ','التدهور','دوهيم','النص والتجربة','فض'],8:['الإنسان','الاستخلاف','الوسع','الابتلاء','ماسلو'],9:['المعرفة','الفطرة','التثبت','التدبر','كانمان','سايمون'],10:['القيم','الرحمة','الحكمة','الصدق','السباعية','التكامل'],
11:['QMF','الإطار','المكوّن','المكون','السلطة','المساءلة','الغاية','المؤسسة','الغياب'],12:['الدورة','الاستشعار','العزم','التوكل','المتابعة','سجل القرار','الاختصار'],13:['المعايير','التسعة','معيار','التطوير','القاعدة'],14:['الحالات','حالة','الحالة']}
pat=re.compile(r'الفصل (الحادي عشر|الثاني عشر|الثالث عشر|الرابع عشر|الأول|الثاني|الثالث|الرابع|الخامس|السادس|السابع|الثامن|التاسع|العاشر)(?! عشر)')
n=0
for ch,sec,s in U:
    for m in pat.finditer(s):
        x=ORD[m.group(1)]
        ctx=s[max(0,m.start()-90):m.end()+60]
        if str(x)==ch: continue
        own=any(k in ctx for k in KW[x])
        if not own:
            n+=1; print(ch,sec,'→',x,'::',ctx.replace('\n',' '))
print(n)
