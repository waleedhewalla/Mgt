def runs_of(p):
    return [r for r in p.findall(q('r')) if ''.join(t.text or '' for t in r.iter(q('t')))]


def labelled(p, label, text):
    """Bold label run + plain text run (numbered items, concept entries, ladder levels)."""
    r = runs_of(p)
    set_runs(p, [(label, r[0]), (text, r[1])])
    return p


def para(like, text):
    p = fresh(copy.deepcopy(K[like])); set_text(p, text); return p


def lab(like, label, text):
    return labelled(fresh(copy.deepcopy(K[like])), label, text)


def blank():
    return fresh(copy.deepcopy(K[17]))


def table(data):
    """Two-column table cloned from the manuscript's summary table; first row is the header."""
    t = fresh(copy.deepcopy(K[3078]))
    while len(t.findall(q('tr'))) > len(data):
        delete_row(t, len(t.findall(q('tr'))) - 1)
    while len(t.findall(q('tr'))) < len(data):
        add_row(t, 1, ['', ''])
    for r, row in enumerate(data):
        for c, text in enumerate(row):
            cell_text(t, r, c, text)
    return t


def heading(text):
    return [blank(), para(18, text), blank()]


